"""
Step 2 - exploratory data analysis.

    python src/eda.py

Answers all 20 questions from the brief (plus the four Step-2 analyses),
saves every chart to reports/figures/ and writes the takeaways to
reports/eda_findings.md so they can go straight into the project report.

Charts are saved as interactive HTML. If kaleido + Chrome are available
they're also saved as PNG (handy for the README).
"""

import os
import re
import shutil
import time

import pandas as pd

from config import CLEAN_PARQUET, FIGURES_DIR, REPORTS_DIR
from eda_questions import QUESTIONS, EXTRAS


def _png_ok() -> bool:
    try:
        import kaleido  # noqa: F401
    except ImportError:
        return False
    # kaleido needs a Chrome; fall back to any chromium on PATH
    if not os.environ.get("BROWSER_PATH"):
        for name in ("google-chrome", "chromium", "chromium-browser"):
            if shutil.which(name):
                os.environ["BROWSER_PATH"] = shutil.which(name)
                break
    return True


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:50]


def main():
    df = pd.read_parquet(CLEAN_PARQUET)
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    png = _png_ok()

    lines = ["# EDA findings", "",
             f"_Generated by `src/eda.py` on {time.strftime('%d %b %Y')} from "
             f"{len(df):,} cleaned listings._", ""]

    section = None
    for group, num, question, fn in QUESTIONS:
        if group != section:
            lines += [f"## {group}", ""]
            section = group
        fig, note = fn(df)
        name = f"q{num:02d}_{slug(question)}"
        fig.write_html(FIGURES_DIR / f"{name}.html", include_plotlyjs="cdn")
        if png:
            try:
                fig.write_image(FIGURES_DIR / f"{name}.png", width=1000, height=fig.layout.height or 520, scale=1.5)
            except Exception as err:   # no Chrome - HTML is enough
                print(f"  (PNG export skipped: {err.__class__.__name__})")
                png = False
        lines += [f"**{num}. {question}**  ", note, ""]
        print(f"Q{num:>2}  {note[:95]}...")

    lines += ["## Step 2 analyses from the brief", ""]
    for title, fn in EXTRAS:
        fig, note = fn(df)
        name = f"x_{slug(title)}"
        fig.write_html(FIGURES_DIR / f"{name}.html", include_plotlyjs="cdn")
        if png:
            fig.write_image(FIGURES_DIR / f"{name}.png", width=1000, height=fig.layout.height or 520, scale=1.5)
        lines += [f"**{title}**  ", note, ""]
        print(f"  +  {note[:95]}...")

    (REPORTS_DIR / "eda_findings.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nCharts -> {FIGURES_DIR}\nFindings -> {REPORTS_DIR / 'eda_findings.md'}")


if __name__ == "__main__":
    main()
